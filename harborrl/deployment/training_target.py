"""TrainingTarget (P1): launch, query and cancel one Slime training job.

``local`` keeps the legacy in-process launcher byte-for-byte. ``ssh`` runs the
same launcher script on the GPU machine through shared storage: the run
directory is written by the manager, executed by the GPU target, and polled
without holding an interactive session open.
"""
from __future__ import annotations

import os
import shlex
import signal
import subprocess
import sys
import time
from pathlib import Path

from harborrl.deployment import remote
from harborrl.deployment.schema import destination

LAUNCHER_NAME = "gpu-launcher.sh"
EXIT_CODE_NAME = "exit-code"
PID_NAME = "launcher.pid"
STDOUT_NAME = "train-stdout.log"


class TrainingTargetError(RuntimeError):
    pass


class LocalTrainingTarget:
    """Legacy target: the Slime job runs as a child of this process."""

    def __init__(self, command, *, cwd, env):
        self.command = [str(part) for part in command]
        self.cwd = str(cwd)
        self.env = env
        self.child = None

    def launch(self):
        self.child = subprocess.Popen(self.command, cwd=self.cwd, env=self.env,
                                      start_new_session=True)
        return self.child.pid

    def wait(self):
        if self.child is None:
            raise TrainingTargetError("local target was never launched")

        def forward_signal(signum, frame):
            if self.child.poll() is None:
                try:
                    os.killpg(os.getpgid(self.child.pid), signum)
                except ProcessLookupError:
                    pass

        previous = {sig: signal.signal(sig, forward_signal)
                    for sig in (signal.SIGINT, signal.SIGTERM)}
        try:
            return self.child.wait()
        finally:
            for sig, handler in previous.items():
                signal.signal(sig, handler)

    def query(self):
        if self.child is None:
            return {"state": "not-launched"}
        return {"state": "running" if self.child.poll() is None else "exited",
                "exit_code": self.child.returncode}

    def cancel(self):
        if self.child is None or self.child.poll() is not None:
            return False
        try:
            os.killpg(os.getpgid(self.child.pid), signal.SIGINT)
        except (ProcessLookupError, PermissionError):
            self.child.terminate()
        return True


class SshTrainingTarget:
    """Remote target over shared storage; the launcher script is the contract."""

    def __init__(self, spec, *, source_dir, run_dir, environment_file=None,
                 command_timeout=60, ssh_timeout=15, poll_interval=2.0):
        self.spec = dict(spec)
        self.source_dir = str(source_dir)
        self.run_dir = Path(run_dir).resolve()
        self.environment_file = environment_file
        self.command_timeout = command_timeout
        self.ssh_timeout = ssh_timeout
        self.poll_interval = poll_interval
        self._launched = False

    def write_launcher(self, command, environment, *, path_rewrites=()):
        """Materialize the launcher; env values and paths are quoted, never interpolated."""
        command = [str(part) for part in command]
        for manager_path, target_path in path_rewrites:
            command = [str(part).replace(str(manager_path), str(target_path), 1)
                       if str(part).startswith(str(manager_path)) else part for part in command]
        lines = ["#!/usr/bin/env bash",
                 "# Generated by the HarborRL manager; executed on the GPU target.",
                 "set -uo pipefail",
                 f"cd {shlex.quote(self.source_dir)}",
                 f"export RUN_DIR={shlex.quote(str(self.run_dir))}"]
        if self.environment_file:
            # A controlled JSON mapping only; never an arbitrary remote shell.
            quoted_file = shlex.quote(str(self.environment_file))
            lines.append(
                "eval \"$(HARBORRL_ENV_FILE=" + quoted_file + " python3 - <<'HARBORRL_ENV_JSON'\n"
                "import json, os, shlex\n"
                "with open(os.environ['HARBORRL_ENV_FILE']) as stream:\n"
                "    for key, value in sorted(json.load(stream).items()):\n"
                "        print(f'export {key}={shlex.quote(str(value))}')\n"
                "HARBORRL_ENV_JSON\n"
                ")\"")
        for key in sorted(environment):
            lines.append(f"export {key}={shlex.quote(str(environment[key]))}")
        lines.append("status=0")
        # The command is a full argv (its first word is already the
        # interpreter); execute it as-is and capture the real exit code.
        lines.append(" ".join(shlex.quote(part) for part in command)
                     + " || status=$?")
        lines.append(f"printf '%s\\n' \"$status\" > {shlex.quote(str(self.run_dir / EXIT_CODE_NAME))}")
        lines.append("exit \"$status\"")
        launcher = self.run_dir / LAUNCHER_NAME
        launcher.write_text("\n".join(lines) + "\n")
        launcher.chmod(0o755)
        return launcher

    def launch(self):
        if self._launched:
            raise TrainingTargetError("ssh target was already launched")
        # The background job records its own session-leader pid: setsid execs
        # the launcher, so the recorded pid heads the cancellable process group.
        bootstrap = (f"cd {shlex.quote(str(self.run_dir))} && "
                     f"(setsid nohup bash {LAUNCHER_NAME} > {STDOUT_NAME} 2>&1"
                     f" < /dev/null & echo $! > {PID_NAME})")
        result = remote.run_ssh(self.spec, bootstrap, timeout=self.command_timeout,
                                connect_timeout=self.ssh_timeout)
        if result.returncode != 0:
            raise TrainingTargetError(
                f"remote launch failed on {destination(self.spec)}: "
                f"{result.stderr.strip()[-500:]}")
        self._launched = True
        return self.run_dir / PID_NAME

    def _pid(self):
        try:
            return int((self.run_dir / PID_NAME).read_text().strip())
        except (OSError, ValueError):
            return None

    def exit_code(self):
        try:
            return int((self.run_dir / EXIT_CODE_NAME).read_text().strip())
        except (OSError, ValueError):
            return None

    def alive(self):
        pid = self._pid()
        if pid is None:
            return False
        result = remote.run_ssh(self.spec, f"kill -0 {pid} 2>/dev/null && echo ok",
                                timeout=self.command_timeout, connect_timeout=self.ssh_timeout)
        return result.returncode == 0 and result.stdout.strip() == "ok"

    def wait(self, *, timeout=None):
        """Poll the shared exit-code record; never resubmit or restart."""
        deadline = None if timeout is None else time.monotonic() + timeout
        while True:
            code = self.exit_code()
            if code is not None:
                return code
            if deadline is not None and time.monotonic() >= deadline:
                raise TimeoutError(f"GPU job in {self.run_dir} did not finish in time")
            time.sleep(self.poll_interval)

    def query(self):
        code = self.exit_code()
        return {"state": "exited" if code is not None else
                ("running" if self.alive() else "unknown"),
                "exit_code": code, "pid": self._pid(),
                "run_dir": str(self.run_dir)}

    def cancel(self, *, grace_seconds=30):
        pid = self._pid()
        if pid is None:
            return False
        for signame in ("INT", "TERM", "KILL"):
            remote.run_ssh(self.spec, f"kill -{signame} -- -{pid} 2>/dev/null || "
                                       f"kill -{signame} {pid} 2>/dev/null || true",
                           timeout=self.command_timeout, connect_timeout=self.ssh_timeout)
            deadline = time.monotonic() + grace_seconds
            while time.monotonic() < deadline:
                if self.exit_code() is not None:
                    return True
                time.sleep(min(2.0, self.poll_interval))
        return self.exit_code() is not None


def local_target(plan, *, environment):
    """Build the legacy in-process target from a resolved plan."""
    allowed = {"PATH", "HOME", "USER", "LANG", "LC_ALL", "TMPDIR", "LD_LIBRARY_PATH",
               "LD_PRELOAD", "CUDA_HOME", "NVTE_CUDA_INCLUDE_DIR",
               "CUDA_VISIBLE_DEVICES", "HTTP_PROXY", "HTTPS_PROXY", "NO_PROXY",
               "http_proxy", "https_proxy", "no_proxy", "PYTHONPATH",
               "SLIME_DIR", "MEGATRON_DIR", "SGLANG_IMAGE"}
    child_env = {key: value for key, value in os.environ.items() if key in allowed}
    child_env["PATH"] = os.pathsep.join(
        [str(Path(sys.executable).parent), child_env.get("PATH", os.defpath)])
    child_env["PYTHONPATH"] = os.pathsep.join(filter(None, [
        child_env.get("SLIME_DIR", ""), child_env.get("MEGATRON_DIR", ""),
        str(Path(__file__).resolve().parents[2]), child_env.get("PYTHONPATH", ""),
    ]))
    child_env.update(environment)
    from harborrl.config import ROOT

    return LocalTrainingTarget(plan["training_command"], cwd=ROOT, env=child_env)
